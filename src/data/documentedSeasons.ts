export function mergeWithDocumentedSeasons(dbSeasons: Season[]): Season[] {
  const byNumber = new Map<number, Season>();
  for (const doc of DOCUMENTED_SEASONS_FALLBACK) {
    byNumber.set(doc.season_number, doc);
  }
  for (const db of dbSeasons) {
    byNumber.set(db.season_number, db);
  }
  return Array.from(byNumber.values()).sort((a, b) => a.season_number - b.season_number);
}
